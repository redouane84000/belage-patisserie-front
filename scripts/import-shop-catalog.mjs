import { mkdir, rm, writeFile } from 'node:fs/promises'
import { createHash } from 'node:crypto'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('..', import.meta.url))
const outputDirectory = path.join(root, 'src', 'data', 'shop')
const mediaDirectory = path.join(root, 'public', 'shop')
const sourceUrl = 'https://www.paulinecake.ae/order'
const AED_TO_EUR = 0.2357
const ALLOWED_CATEGORIES = new Map([
  ['Standard cakes', { id: 'standard-cakes', title: 'Gâteaux classiques' }],
  ['XS cakes', { id: 'xs-cakes', title: 'Gâteaux XS' }],
  ['Italian pie', { id: 'italian-cake', title: 'Gâteaux italiens' }],
  ['Kids cakes', { id: 'kids-cakes', title: 'Gâteaux enfants' }],
  ['Custom cakes', { id: 'custom-cakes', title: 'Gâteaux sur mesure' }],
  ['Kids custom cakes', { id: 'kids-custom-cakes', title: 'Gâteaux sur mesure enfants' }],
])

const slugify = (value) => value
  .normalize('NFD')
  .replace(/[\u0300-\u036f]/g, '')
  .toLowerCase()
  .replace(/[^a-z0-9]+/g, '-')
  .replace(/^-|-$/g, '')

const isGlitter = (value = '') => /glitter|paillettes/i.test(value)
const toEuroCents = (aedCents) => {
  const euros = (aedCents / 100) * AED_TO_EUR
  return Math.round(Math.round(euros * 2) / 2 * 100)
}

function extensionFrom(contentType) {
  if (contentType?.includes('png')) return 'png'
  if (contentType?.includes('webp')) return 'webp'
  if (contentType?.includes('gif')) return 'gif'
  return 'jpg'
}

const downloadedImages = new Map()

async function downloadImage(url) {
  if (!url) return null
  if (downloadedImages.has(url)) return downloadedImages.get(url)

  const optimizedUrl = `https://www.paulinecake.ae/_next/image?url=${encodeURIComponent(url)}&w=828&q=75`
  const response = await fetch(optimizedUrl)
  if (!response.ok) throw new Error(`Image inaccessible (${response.status}) : ${url}`)

  const extension = extensionFrom(response.headers.get('content-type'))
  const fileName = `${createHash('sha256').update(url).digest('hex').slice(0, 16)}.${extension}`
  const localPath = `/shop/media/${fileName}`
  await writeFile(path.join(mediaDirectory, 'media', fileName), Buffer.from(await response.arrayBuffer()))
  downloadedImages.set(url, localPath)
  return localPath
}

async function normalizeModification(modification) {
  if (isGlitter(modification.name)) return null

  const items = modification.items
    .filter((item) => !isGlitter(item.name))
  const values = await Promise.all(items.map(async (item) => ({
    id: slugify(item.name),
    label: item.name,
    description: item.description ?? '',
    image: await downloadImage(item.image),
    priceAEDCents: item.price,
    priceCents: toEuroCents(item.price),
  })))

  if (!values.length) return null

  return {
    id: slugify(modification.name),
    label: modification.name,
    required: modification.required,
    type: modification.type,
    values,
  }
}

async function importCatalog() {
  const response = await fetch(sourceUrl)
  if (!response.ok) throw new Error(`Catalogue inaccessible (${response.status})`)

  const html = await response.text()
  const match = html.match(/<script id="__NEXT_DATA__" type="application\/json">([\s\S]*?)<\/script>/)
  if (!match) throw new Error('Les données structurées du catalogue sont introuvables.')

  const { menu } = JSON.parse(match[1]).props.pageProps
  await mkdir(outputDirectory, { recursive: true })
  await rm(mediaDirectory, { recursive: true, force: true })
  await mkdir(path.join(mediaDirectory, 'media'), { recursive: true })

  const categories = []

  for (const { category, items } of menu) {
    const mappedCategory = ALLOWED_CATEGORIES.get(category.name)
    if (!mappedCategory) continue

    const products = []
    for (const item of items) {
      if (mappedCategory.id === 'standard-cakes' && item.name.trim().toLowerCase() === 'napoleon') continue

      const productId = `${mappedCategory.id}-${slugify(item.name)}`
      const sourceImages = [item.photo, ...(item.gallery ?? [])].filter(Boolean)
      const images = [...new Set(await Promise.all(sourceImages.map(downloadImage)))]
      const options = (await Promise.all((item.modifications ?? []).map(normalizeModification))).filter(Boolean)

      products.push({
        id: productId,
        slug: productId,
        name: item.name.trim(),
        description: item.description ?? '',
        preparation: category.tag ? `${category.tag}${category.description ? ` — ${category.description}` : ''}` : '',
        image: images[0],
        images,
        basePriceAEDCents: item.price,
        basePriceCents: toEuroCents(item.price),
        options,
      })
    }

    categories.push({
      ...mappedCategory,
      tag: category.tag ?? '',
      description: category.description ?? '',
      products,
    })
  }

  const file = `// Generated by scripts/import-shop-catalog.mjs. Do not edit manually.\n`
    + `import { localizeCatalog } from './frenchCatalog.js'\n`
    + `export const AED_TO_EUR = ${AED_TO_EUR}\n`
    + `export const SHOP_CATEGORIES = localizeCatalog(${JSON.stringify(categories, null, 2)})\n`
    + `export const SHOP_PRODUCTS = SHOP_CATEGORIES.flatMap((category) => category.products.map((product) => ({ ...product, categoryId: category.id })))\n`

  await writeFile(path.join(outputDirectory, 'catalog.generated.js'), file)
  console.log(`Catalogue importé : ${categories.reduce((count, category) => count + category.products.length, 0)} produits.`)
}

importCatalog().catch((error) => {
  console.error(error.message)
  process.exitCode = 1
})
