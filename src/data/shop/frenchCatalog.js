function translateValueDescription(description) {
  if (!description) return ''
  const text = description
    .replace(/Weight\s*[–—-]\s*/gi, 'Poids — ')
    .replace(/Size\s*[–—-]\s*/gi, 'Dimensions — ')
    .replace(/Cakeboard\s*[–—-]\s*/gi, 'Plateau — ')
    .replace(/diameter/gi, 'diamètre')
    .replace(/height/gi, 'hauteur')
    .replace(/There are (\d+) pieces in the one set\./gi, 'Un lot contient $1 pièces.')
    .replace(/pieces/gi, 'pièces')
  return /[a-z]{3,}/i.test(text.replace(/poids|dimensions|plateau|diamètre|hauteur|un|lot|contient|pièces/gi, '')) ? '' : text
}

export function localizeCatalog(categories) {
  return categories.map((category) => {
    const localized = CATEGORY_COPY[category.id] ?? {}
    return {
      ...category,
      title: localized.title ?? category.title,
      tag: localized.tag ?? '',
      description: localized.description ?? '',
      products: category.products.map((product) => ({
        ...product,
        image: product.images.find((image) => !isPaulineMedia(image)) ?? null,
        images: product.images.filter((image) => !isPaulineMedia(image)),
        name: PRODUCT_NAMES[product.id] ?? product.name,
        description: product.id === 'standard-cakes-signature-tasting-box'
          ? 'Un coffret dégustation raffiné réunissant huit parts de nos créations emblématiques, accompagné de thé, de couverts et de serviettes. Une belle façon de découvrir ou de partager vos saveurs favorites.'
          : (localized.productDescription ?? ''),
        preparation: localized.tag ?? '',
        options: product.options.map((option) => ({
          ...option,
          label: OPTION_LABELS[option.id] ?? option.label,
          values: [
            ...option.values,
            ...(option.id.includes('flavor') && !option.values.some((value) => value.id === 'nutella-kinder')
              ? [NUTELLA_KINDER_FLAVOR]
              : []),
          ].map(translateValue),
        })),
      })),
    }
  })
}
